def describe(name):
    if name in GD: return GD[name]
    m = re.match(r'(BrakeTemperature|TyrePressure|TyreTemperature|TyreWear|TyreDirt|LastLapTyreWear)(FrontLeft|FrontRight|RearLeft|RearRight)(Inner|Middle|Outer)?$', name)
    if m:
        what = {'BrakeTemperature': 'Temperatura do freio', 'TyrePressure': 'Pressao do pneu', 'TyreTemperature': 'Temperatura do pneu',
                'TyreWear': 'Desgaste do pneu (0-100, 100 = novo na maioria dos jogos)', 'TyreDirt': 'Sujeira no pneu',
                'LastLapTyreWear': 'Desgaste do pneu na ultima volta'}[m.group(1)]
        s = '%s %s' % (what, POS[m.group(2)])
        if m.group(3): s += ', %s da banda' % ZONE[m.group(3)]
        elif m.group(1) == 'TyreTemperature': s += ' (nucleo/media)'
        return s + '.'
    m = re.match(r'(Brakes|Tyres)(Temperature|Wear|DirtyLevel)(Avg|Max|Min)$', name)
    if m:
        a = {'Avg': 'Media', 'Max': 'Maximo', 'Min': 'Minimo'}[m.group(3)]
        w = {('Brakes', 'Temperature'): 'das temperaturas de freio', ('Tyres', 'Temperature'): 'das temperaturas de pneu',
             ('Tyres', 'Wear'): 'do desgaste dos pneus', ('Tyres', 'DirtyLevel'): 'da sujeira dos pneus'}[(m.group(1), m.group(2))]
        return '%s %s (calculado).' % (a, w)
    m = re.match(r'Sector(\d)(LastLapTime|BestLapTime|BestTime)$', name)
    if m:
        k = {'LastLapTime': 'na ultima volta', 'BestLapTime': 'na melhor volta', 'BestTime': 'melhor da sessao (setor isolado)'}[m.group(2)]
        return 'Tempo do setor %s %s.' % (m.group(1), k)
    return ''

